// silence is how long a replay waits to be sure no frame follows.
const silence = 400 * time.Millisecond

type frameExchange struct {
	label string
	frame []byte // sent by the machine
	reply []byte // nil: the server sends nothing
}

type frameTranscript struct {
	bootp     string // the "bootp" line: run the BOOTP service for this client; empty for none
	exchanges []frameExchange
}

// parseFrameTranscript reads the line format: optional "bootp" line, then
// for each exchange a "frame LABEL" line, the machine's frame on "> " lines,
// and the server's answer on "< " lines or a single "none" line. Blank lines
// and lines starting with "#" are ignored.
func parseFrameTranscript(data []byte) (frameTranscript, error) {
	var tr frameTranscript
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, rest, _ := strings.Cut(line, " ")
		switch key {
		case "server":
			if strings.TrimSpace(rest) != transcriptServer {
				return tr, fmt.Errorf("line %d: server %q, want %q", n, rest, transcriptServer)
			}
		case "bootp":
			if _, err := parseBootpLine(rest); err != nil {
				return tr, fmt.Errorf("line %d: %v", n, err)
			}
			tr.bootp = strings.TrimSpace(rest)
		case "frame":
			tr.exchanges = append(tr.exchanges, frameExchange{label: strings.TrimSpace(rest)})
		case "none":
			if len(tr.exchanges) == 0 {
				return tr, fmt.Errorf("line %d: none before any frame", n)
			}
		case ">", "<":
			if len(tr.exchanges) == 0 {
				return tr, fmt.Errorf("line %d: bytes before any frame", n)
			}
			b, err := hex.DecodeString(strings.Join(strings.Fields(rest), ""))
			if err != nil {
				return tr, fmt.Errorf("line %d: %v", n, err)
			}
			ex := &tr.exchanges[len(tr.exchanges)-1]
			if key == ">" {
				ex.frame = append(ex.frame, b...)
			} else {
				ex.reply = append(ex.reply, b...)
			}
		default:
			return tr, fmt.Errorf("line %d: unknown keyword %q", n, key)
		}
	}
	return tr, sc.Err()
}

// The segment every transcript runs on.
const (
	transcriptServer = "10.98.0.2/24 08:00:69:00:00:02"
	transcriptBootp  = "08:00:69:12:34:56 10.98.0.65"

	transcriptHostname = "origin200"
)

// bootpLine is the "bootp" line: the one client the service answers and
// whether it also answers DHCP.
type bootpLine struct {
	hostname string
	dhcp     bool
	serverID netip.Addr
}

// parseBootpLine accepts the fixed client, then any of hostname=NAME, dhcp
// and server-id=ADDR.
func parseBootpLine(rest string) (bootpLine, error) {
	var bl bootpLine
	f := strings.Fields(rest)
	if len(f) < 2 || f[0]+" "+f[1] != transcriptBootp {
		return bl, fmt.Errorf("bootp %q, want %q first", rest, transcriptBootp)
	}
	for _, w := range f[2:] {
		switch {
		case w == "dhcp":
			bl.dhcp = true
		case w == "hostname="+transcriptHostname:
			bl.hostname = transcriptHostname
		case strings.HasPrefix(w, "server-id="):
			id, err := netip.ParseAddr(strings.TrimPrefix(w, "server-id="))
			if err != nil {
				return bl, fmt.Errorf("bootp: %q: %v", w, err)
			}
			bl.serverID = id
		default:
			return bl, fmt.Errorf("bootp: unknown option %q", w)
		}
	}
	return bl, nil
}

func (tr frameTranscript) format(name, about string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s: generated by go test ./internal/qemunet -run TestFrameTranscripts -update\n", name)
	for _, l := range strings.Split(about, "\n") {
		fmt.Fprintf(&b, "# %s\n", l)
	}
	fmt.Fprintf(&b, "server %s\n", transcriptServer)
	if tr.bootp != "" {
		fmt.Fprintf(&b, "bootp %s\n", tr.bootp)
	}
	for _, ex := range tr.exchanges {
		fmt.Fprintf(&b, "\nframe %s\n", ex.label)
		writeFrameHex(&b, "> ", ex.frame)
		if ex.reply == nil {
			b.WriteString("none\n")
		} else {
			writeFrameHex(&b, "< ", ex.reply)
		}
	}
	return b.Bytes()
}

// writeFrameHex writes p as 4-byte words, eight to a line.
func writeFrameHex(b *bytes.Buffer, prefix string, p []byte) {
	for len(p) > 0 {
		line := p[:min(32, len(p))]
		p = p[len(line):]
		b.WriteString(strings.TrimSpace(prefix))
		for len(line) > 0 {
			w := line[:min(4, len(line))]
			line = line[len(w):]
			b.WriteString(" " + hex.EncodeToString(w))
		}
		b.WriteByte('\n')
	}
}

// replayNetwork brings up the segment a transcript describes and returns
// the machine's end of the stream.
func replayNetwork(t *testing.T, bootpSpec string) net.Conn {
	t.Helper()
	conn, peer := net.Pipe()
	n, err := New(conn, Config{ServerIP: netip.AddrFrom4(testSrvIP), PrefixLen: 24, MAC: net.HardwareAddr([]byte(testSrvMAC))})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { peer.Close(); n.Close() })
	if bootpSpec != "" {
		pc, err := n.ListenPacket(67)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { pc.Close() })
		bs := &bootp.Server{
			ServerIP: netip.AddrFrom4(testSrvIP),
			Netmask:  netip.MustParsePrefix("10.98.0.0/24"),
			Clients:  []bootp.Client{{Name: "guest", MAC: net.HardwareAddr([]byte(testGstMAC)), IP: netip.AddrFrom4(testGstIP)}},
		}
		bl, err := parseBootpLine(bootpSpec)
		if err != nil {
			t.Fatal(err)
		}
		bs.Clients[0].Hostname = bl.hostname
		bs.DHCP = bl.dhcp
		bs.DHCPServerID = bl.serverID
		go bs.Serve(pc)
	}
	return peer
}

// replay sends each exchange's frame in the stream framing and returns what
// the server answered, nil for silence.
func replay(t *testing.T, tr frameTranscript) [][]byte {
	t.Helper()
	peer := replayNetwork(t, tr.bootp)
	w := frameWriter{w: peer}
	// A reader goroutine, so silence is a timeout and not a stuck Read.
	frames := make(chan []byte, 16)
	go func() {
		r := frameReader{r: peer}
		for {
			f, err := r.read(maxFrame)
			if err != nil {
				close(frames)
				return
			}
			frames <- append([]byte(nil), f...)
		}
	}()
	var out [][]byte
	for _, ex := range tr.exchanges {
		if err := w.write(ex.frame); err != nil {
			t.Fatalf("%s: %v", ex.label, err)
		}
		select {
		case f, ok := <-frames:
			if !ok {
				t.Fatalf("%s: stream closed", ex.label)
			}
			out = append(out, normalizeFrame(f))
		case <-time.After(silence):
			out = append(out, nil)
		}
	}
	return out
}

// normalizeFrame zeroes the IPv4 identification of a frame the host
// originated and recomputes the header checksum. The host picks the
// identification at random, so it is no part of the contract; a replay
// does the same to the frame it receives before comparing.
func normalizeFrame(f []byte) []byte {
	if len(f) < 34 || binary.BigEndian.Uint16(f[12:14]) != 0x0800 {
		return f
	}
	ihl := int(f[14]&15) * 4
	if f[14]>>4 != 4 || ihl < 20 || len(f) < 14+ihl {
		return f
	}
	out := append([]byte(nil), f...)
	out[18], out[19] = 0, 0
	out[24], out[25] = 0, 0
	binary.BigEndian.PutUint16(out[24:], wireChecksum(out[14:14+ihl]))
	return out
}

