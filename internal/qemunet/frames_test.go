func TestFrameTranscripts(t *testing.T) {
	for _, sc := range frameScenarios {
		t.Run(sc.file, func(t *testing.T) {
			path := filepath.Join(frameTranscriptDir, sc.file)
			tr := frameTranscript{bootp: sc.bootp, exchanges: sc.exchanges}
			if *update {
				replies := replay(t, tr)
				for i := range tr.exchanges {
					tr.exchanges[i].reply = replies[i]
				}
				if err := os.MkdirAll(frameTranscriptDir, 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, tr.format(sc.file, sc.about), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			// The file is what the stack produced for the scenario.
			parsed, err := parseFrameTranscript(data)
			if err != nil {
				t.Fatal(err)
			}
			if len(parsed.exchanges) != len(sc.exchanges) {
				t.Fatalf("%s has %d exchanges, the scenario %d: run with -update", sc.file, len(parsed.exchanges), len(sc.exchanges))
			}
			for i, ex := range sc.exchanges {
				if !bytes.Equal(parsed.exchanges[i].frame, ex.frame) {
					t.Errorf("%s: frame differs from the scenario: run with -update", ex.label)
				}
			}
			// Replay the file's raw bytes.
			got := replay(t, parsed)
			for i, ex := range parsed.exchanges {
				if !bytes.Equal(got[i], ex.reply) {
					t.Errorf("%s: reply\n got %x\nwant %x", ex.label, got[i], ex.reply)
				}
			}
		})
	}
}

