func ethFrame(dst, src []byte, ethertype uint16, payload []byte) []byte {
	f := append(append(append([]byte(nil), dst...), src...), byte(ethertype>>8), byte(ethertype))
	f = append(f, payload...)
	for len(f) < 60 {
		f = append(f, 0)
	}
	return f
}

func arpMsg(op uint16, sha []byte, spa [4]byte, tha []byte, tpa [4]byte) []byte {
	p := []byte{0, 1, 8, 0, 6, 4, byte(op >> 8), byte(op)}
	p = append(p, sha...)
	p = append(p, spa[:]...)
	p = append(p, tha...)
	return append(p, tpa[:]...)
}

func ipv4Packet(src, dst [4]byte, proto byte, id uint16, ttl byte, payload []byte) []byte {
	h := make([]byte, 20)
	h[0] = 0x45
	binary.BigEndian.PutUint16(h[2:], uint16(20+len(payload)))
	binary.BigEndian.PutUint16(h[4:], id)
	h[8], h[9] = ttl, proto
	copy(h[12:], src[:])
	copy(h[16:], dst[:])
	binary.BigEndian.PutUint16(h[10:], wireChecksum(h))
	return append(h, payload...)
}

func icmpEcho(typ byte, id, seq uint16, data []byte) []byte {
	m := []byte{typ, 0, 0, 0, byte(id >> 8), byte(id), byte(seq >> 8), byte(seq)}
	m = append(m, data...)
	binary.BigEndian.PutUint16(m[2:], wireChecksum(m))
	return m
}

func udpDatagram(src, dst [4]byte, sport, dport uint16, payload []byte) []byte {
	u := make([]byte, 8, 8+len(payload))
	binary.BigEndian.PutUint16(u[0:], sport)
	binary.BigEndian.PutUint16(u[2:], dport)
	binary.BigEndian.PutUint16(u[4:], uint16(8+len(payload)))
	u = append(u, payload...)
	pseudo := append(append(append([]byte(nil), src[:]...), dst[:]...), 0, 17, byte(len(u)>>8), byte(len(u)))
	sum := wireChecksum(append(pseudo, u...))
	if sum == 0 {
		sum = 0xffff
	}
	binary.BigEndian.PutUint16(u[6:], sum)
	return u
}

