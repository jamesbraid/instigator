var update = flag.Bool("update", false, "rewrite testdata/transcripts from the scenarios")

const transcriptDir = "testdata/transcripts"

// The ports portmap advertises in every transcript, on both transports.
// The harness binds ephemeral ports, so these are only the values the
// replies carry.
var transcriptPorts = nfs.Ports{Portmap: 111, Mount: 635, NFS: 2049}

type exchange struct {
	label       string
	call, reply []byte
}

type transcript struct {
	fixture   string
	exchanges []exchange
}

// parseTranscript reads the line format: "fixture NAME", then for each
// exchange a "call LABEL" line, its call bytes on "> " lines and its
// reply bytes on "< " lines, as whitespace-separated hex. Blank lines and
// lines starting with "#" are ignored.
func parseTranscript(data []byte) (transcript, error) {
	var tr transcript
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, rest, _ := strings.Cut(line, " ")
		switch key {
		case "fixture":
			tr.fixture = strings.TrimSpace(rest)
		case "call":
			tr.exchanges = append(tr.exchanges, exchange{label: strings.TrimSpace(rest)})
		case ">", "<":
			if len(tr.exchanges) == 0 {
				return tr, fmt.Errorf("line %d: bytes before any call", n)
			}
			b, err := hex.DecodeString(strings.Join(strings.Fields(rest), ""))
			if err != nil {
				return tr, fmt.Errorf("line %d: %v", n, err)
			}
			ex := &tr.exchanges[len(tr.exchanges)-1]
			if key == ">" {
				ex.call = append(ex.call, b...)
			} else {
				ex.reply = append(ex.reply, b...)
			}
		default:
			return tr, fmt.Errorf("line %d: unknown keyword %q", n, key)
		}
	}
	return tr, sc.Err()
}

func (tr transcript) format(name string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s: generated by go test ./nfs -run TestTranscripts -update\n", name)
	fmt.Fprintf(&b, "fixture %s\n", tr.fixture)
	for _, ex := range tr.exchanges {
		fmt.Fprintf(&b, "\ncall %s\n", ex.label)
		writeHex(&b, "> ", ex.call)
		writeHex(&b, "< ", ex.reply)
	}
	return b.Bytes()
}

// writeHex writes p as 4-byte XDR words, eight to a line.
func writeHex(b *bytes.Buffer, prefix string, p []byte) {
	for len(p) > 0 {
		line := p[:min(32, len(p))]
		p = p[len(line):]
		b.WriteString(strings.TrimSpace(prefix))
		for len(line) > 0 {
			w := line[:min(4, len(line))]
			line = line[len(w):]
			b.WriteString(" " + hex.EncodeToString(w))
		}
		b.WriteByte('\n')
	}
}

// fixtureFS builds testdata/fixture.txt as an fstest.MapFS.
func fixtureFS(t *testing.T) fstest.MapFS {
	t.Helper()
	data, err := os.ReadFile("testdata/fixture.txt")
	if err != nil {
		t.Fatal(err)
	}
	m := fstest.MapFS{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if len(f) < 4 {
			t.Fatalf("fixture: short line %q", line)
		}
		perm, err1 := strconv.ParseUint(f[2], 8, 32)
		mtime, err2 := strconv.ParseInt(f[3], 10, 64)
		if err := errors.Join(err1, err2); err != nil {
			t.Fatalf("fixture: %q: %v", line, err)
		}
		mf := &fstest.MapFile{Mode: fs.FileMode(perm), ModTime: time.Unix(mtime, 0)}
		switch f[0] {
		case "dir":
			mf.Mode |= fs.ModeDir
		case "file":
			mf.Data = fixtureContent(t, f[4])
		case "link":
			mf.Mode |= fs.ModeSymlink
			mf.Data = []byte(f[4])
		default:
			t.Fatalf("fixture: unknown kind %q", f[0])
		}
		m[f[1]] = mf
	}
	return m
}

func fixtureContent(t *testing.T, spec string) []byte {
	kind, arg, _ := strings.Cut(spec, ":")
	switch kind {
	case "hex":
		b, err := hex.DecodeString(arg)
		if err != nil {
			t.Fatalf("fixture: %q: %v", spec, err)
		}
		return b
	case "pattern":
		n, err := strconv.Atoi(arg)
		if err != nil {
			t.Fatalf("fixture: %q: %v", spec, err)
		}
		b := make([]byte, n)
		for i := range b {
			b[i] = byte(i % 251)
		}
		return b
	}
	t.Fatalf("fixture: unknown content %q", spec)
	return nil
}

// transcriptVerifier is the write verifier of the share fixture's
// server.
var transcriptVerifier = [8]byte{'v', 'e', 'r', 'i', 'f', 'i', 'e', 'r'}

// hostTime stands in, in share transcripts, for every time the host
// chose rather than the fixture or a client.
var hostTime = time.Unix(2000000000, 0)

// hostEpoch divides times: the fixture's are in 1999 and a client's in
// 2001, so anything after it came from the host's clock. A fixed line,
// rather than the test's start, because a file's times come from the
// kernel's coarse clock, which can read earlier than time.Now.
var hostEpoch = time.Unix(1262304000, 0) // 2010-01-01

// pinHostAttrs makes a share's attributes the same on every host. A
// modification time after hostEpoch becomes hostTime, as every change
// time does. The access time is shown as the modification time, since
// whether a read updates it depends on how the host mounts its disk. A
// directory's size and link count, and every file's storage use, depend
// on the host filesystem and are replaced.
func pinHostAttrs(a *nfs.Attr) {
	if a.Mtime.After(hostEpoch) {
		a.Mtime = hostTime
	}
	a.Atime = a.Mtime
	a.Ctime = hostTime
	if a.Mode&0o170000 == 0o040000 {
		a.Size = 4096
		a.Nlink = 2
	}
	a.Used = (a.Size + 4095) &^ 4095
}

// shareFixture writes testdata/fixture.txt to a temporary directory and
// exports it as the share "share", with a path table so its handles and
// fileids don't depend on the host's inode numbers.
func shareFixture(t *testing.T) *sharefs.FS {
	t.Helper()
	base := t.TempDir()
	dir := filepath.Join(base, "share")
	tree := fixtureFS(t)
	paths := make([]string, 0, len(tree))
	for p := range tree {
		paths = append(paths, p)
	}
	sort.Strings(paths) // parents before children
	for _, p := range paths {
		mf, host := tree[p], filepath.Join(dir, filepath.FromSlash(p))
		var err error
		switch {
		case mf.Mode.IsDir():
			err = os.MkdirAll(host, 0o755)
		case mf.Mode&fs.ModeSymlink != 0:
			err = os.Symlink(string(mf.Data), host)
		default:
			err = os.WriteFile(host, mf.Data, 0o644)
		}
		if err != nil {
			t.Fatal(err)
		}
	}
	// Modes and times last, deepest first, since adding an entry to a
	// directory changes its modification time.
	for i := len(paths) - 1; i >= 0; i-- {
		mf, host := tree[paths[i]], filepath.Join(dir, filepath.FromSlash(paths[i]))
		if mf.Mode&fs.ModeSymlink != 0 {
			continue
		}
		if err := errors.Join(os.Chmod(host, mf.Mode), os.Chtimes(host, mf.ModTime, mf.ModTime)); err != nil {
			t.Fatal(err)
		}
	}
	f, err := sharefs.Open("share", dir, sharefs.Options{
		PathTable:  filepath.Join(base, "handles"),
		AttrFilter: pinHostAttrs,
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { f.Close() })
	return f
}

// transcriptServer is one server for one transcript, listening on UDP
// and TCP.
type transcriptServer struct {
	udp, tcp net.Addr
	conn     net.Conn // the TCP connection, opened on first use
}

func startTranscriptServer(t *testing.T, fixture string) *transcriptServer {
	t.Helper()
	var s *nfs.Server
	switch fixture {
	case "tree":
		s = &nfs.Server{FS: nfsexport.Export(fixtureFS(t))}
	case "share":
		s = &nfs.Server{FS: shareFixture(t), Verifier: transcriptVerifier}
	default:
		t.Fatalf("unknown fixture %q", fixture)
	}
	s.SetPorts(transcriptPorts, transcriptPorts)
	pc, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	ts := &transcriptServer{udp: pc.LocalAddr(), tcp: l.Addr()}
	done := make(chan struct{})
	go func() { s.ServeTCP(l); close(done) }()
	go s.ServeUDP(pc)
	t.Cleanup(func() {
		pc.Close()
		l.Close()
		if ts.conn != nil {
			ts.conn.Close()
		}
		<-done
	})
	return ts
}

// roundTrip sends one call over UDP and returns the reply.
func (ts *transcriptServer) roundTrip(t *testing.T, call []byte) []byte {
	t.Helper()
	c, err := net.Dial("udp", ts.udp.String())
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	if _, err := c.Write(call); err != nil {
		t.Fatal(err)
	}
	c.SetReadDeadline(time.Now().Add(5 * time.Second))
	buf := make([]byte, 65536)
	n, err := c.Read(buf)
	if err != nil {
		t.Fatalf("no reply: %v", err)
	}
	return buf[:n]
}

// roundTripTCP sends one call on the transcript's TCP connection, record
// marked, and returns the reply with its mark checked and removed.
func (ts *transcriptServer) roundTripTCP(t *testing.T, call []byte) []byte {
	t.Helper()
	if ts.conn == nil {
		c, err := net.Dial("tcp", ts.tcp.String())
		if err != nil {
			t.Fatal(err)
		}
		ts.conn = c
	}
	ts.conn.SetDeadline(time.Now().Add(5 * time.Second))
	if _, err := ts.conn.Write(binary.BigEndian.AppendUint32(nil, 0x80000000|uint32(len(call)))); err != nil {
		t.Fatal(err)
	}
	if _, err := ts.conn.Write(call); err != nil {
		t.Fatal(err)
	}
	var hdr [4]byte
	if _, err := io.ReadFull(ts.conn, hdr[:]); err != nil {
		t.Fatalf("no reply: %v", err)
	}
	h := binary.BigEndian.Uint32(hdr[:])
	if h&0x80000000 == 0 {
		t.Fatalf("reply fragment not marked last: %#x", h)
	}
	reply := make([]byte, h&0x7fffffff)
	if _, err := io.ReadFull(ts.conn, reply); err != nil {
		t.Fatalf("short reply: %v", err)
	}
	return reply
}

// recorder runs a scenario against a live server, keeping every exchange.
type recorder struct {
	t   *testing.T
	ts  *transcriptServer
	xid uint32
	tr  transcript
}

// Credentials for calls. IRIX sends AUTH_UNIX; the server ignores both.
var (
	authNull = []byte{0, 0, 0, 0, 0, 0, 0, 0}
	authUnix = (&xdr{}).u32(1).opaque((&xdr{}).u32(0).str("irix").u32(0).u32(0).u32(1).u32(0).b).b
)

// callWith sends one call with the given credential and returns the
// reply body after the accepted-reply header, or nil when the call was
// not accepted with SUCCESS.
func (r *recorder) callWith(cred []byte, label string, prog, vers, proc uint32, args []byte) []byte {
	r.t.Helper()
	r.xid++
	call := (&xdr{}).u32(r.xid).u32(0).u32(2).u32(prog).u32(vers).u32(proc).fixed(cred).u32(0).u32(0).fixed(args).b
	reply := r.ts.roundTrip(r.t, call)
	r.tr.exchanges = append(r.tr.exchanges, exchange{label: label, call: call, reply: reply})
	// xid, REPLY, MSG_ACCEPTED, AUTH_NULL verifier, SUCCESS
	if len(reply) < 24 || binary.BigEndian.Uint32(reply[8:]) != 0 || binary.BigEndian.Uint32(reply[20:]) != 0 {
		return nil
	}
	return reply[24:]
}

// raw sends call bytes as they are, for calls the helpers can't build.
func (r *recorder) raw(label string, call []byte) {
	r.t.Helper()
	r.xid++
	reply := r.ts.roundTrip(r.t, call)
	r.tr.exchanges = append(r.tr.exchanges, exchange{label: label, call: call, reply: reply})
}

func (r *recorder) call(label string, prog, vers, proc uint32, args []byte) []byte {
	r.t.Helper()
	return r.callWith(authNull, label, prog, vers, proc, args)
}

// xdr builds call arguments.
type xdr struct{ b []byte }

func (x *xdr) u32(v uint32) *xdr { x.b = binary.BigEndian.AppendUint32(x.b, v); return x }
func (x *xdr) u64(v uint64) *xdr { x.b = binary.BigEndian.AppendUint64(x.b, v); return x }
func (x *xdr) fixed(p []byte) *xdr {
	x.b = append(x.b, p...)
	return x
}
func (x *xdr) opaque(p []byte) *xdr {
	x.u32(uint32(len(p)))
	x.b = append(x.b, p...)
	for len(x.b)%4 != 0 {
		x.b = append(x.b, 0)
	}
	return x
}
func (x *xdr) str(s string) *xdr { return x.opaque([]byte(s)) }

func TestTranscripts(t *testing.T) {
	names := make([]string, 0, len(scenarios))
	for name := range scenarios {
		names = append(names, name)
	}
	sort.Strings(names)

	if !*update {
		// A file nothing generates would be replayed forever without
		// anyone knowing where it came from.
		files, _ := filepath.Glob(filepath.Join(transcriptDir, "*.txt"))
		for _, f := range files {
			if _, ok := scenarios[strings.TrimSuffix(filepath.Base(f), ".txt")]; !ok {
				t.Errorf("%s has no scenario", f)
			}
		}
	}

	for _, name := range names {
		sc := scenarios[name]
		t.Run(name, func(t *testing.T) {
			rec := &recorder{t: t, ts: startTranscriptServer(t, sc.fixture), tr: transcript{fixture: sc.fixture}}
			sc.run(rec)
			path := filepath.Join(transcriptDir, name+".txt")
			got := rec.tr.format(name)
			if *update {
				if err := os.WriteFile(path, got, 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v (run with -update to create it)", err)
			}
			if !bytes.Equal(got, want) {
				t.Errorf("%s is out of date; diff it against a run with -update:\n%s", path, firstDiff(rec.tr, want))
			}
			tr, err := parseTranscript(want)
			if err != nil {
				t.Fatalf("%s: %v", path, err)
			}
			replay(t, tr)
		})
	}
}

// replay sends a transcript's raw call bytes to a fresh server on each
// transport, as another implementation's test would.
func replay(t *testing.T, tr transcript) {
	t.Helper()
	for _, transport := range []string{"udp", "tcp"} {
		ts := startTranscriptServer(t, tr.fixture)
		for _, ex := range tr.exchanges {
			var got []byte
			if transport == "udp" {
				got = ts.roundTrip(t, ex.call)
			} else {
				got = ts.roundTripTCP(t, ex.call)
			}
			if !bytes.Equal(got, ex.reply) {
				t.Fatalf("%s replay %q:\n got %x\nwant %x", transport, ex.label, got, ex.reply)
			}
		}
	}
}

// firstDiff names the first exchange whose bytes changed.
func firstDiff(got transcript, wantFile []byte) string {
	want, err := parseTranscript(wantFile)
	if err != nil {
		return err.Error()
	}
	for i, ex := range got.exchanges {
		if i >= len(want.exchanges) {
			return fmt.Sprintf("new exchange %q", ex.label)
		}
		w := want.exchanges[i]
		if ex.label != w.label || !bytes.Equal(ex.call, w.call) || !bytes.Equal(ex.reply, w.reply) {
			return fmt.Sprintf("exchange %d %q:\n call %x\nreply %x\nwant %q:\n call %x\nreply %x",
				i, ex.label, ex.call, ex.reply, w.label, w.call, w.reply)
		}
	}
	if len(want.exchanges) > len(got.exchanges) {
		return fmt.Sprintf("exchange %q removed", want.exchanges[len(got.exchanges)].label)
	}
	return "header changed"
}

func TestParseTranscript(t *testing.T) {
	tr, err := parseTranscript([]byte("# c\nfixture tree\n\ncall one\n> 00000001 0002\n> 03\n< ff\n"))
	if err != nil {
		t.Fatal(err)
	}
	if tr.fixture != "tree" || len(tr.exchanges) != 1 {
		t.Fatalf("parsed %+v", tr)
	}
	ex := tr.exchanges[0]
	if ex.label != "one" || !bytes.Equal(ex.call, []byte{0, 0, 0, 1, 0, 2, 3}) || !bytes.Equal(ex.reply, []byte{0xff}) {
		t.Fatalf("exchange %+v", ex)
	}
	if _, err := parseTranscript([]byte("> 00\n")); err == nil {
		t.Fatal("bytes before a call parsed")
	}
}
